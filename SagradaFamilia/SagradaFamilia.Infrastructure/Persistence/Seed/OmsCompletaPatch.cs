        public static async Task PatchAsync(AppDbContext context)
        {
            var existentes = await context.OmsReferencias
                .Select(o => new { o.Sexo, o.EdadMeses, o.Tipo })
                .ToListAsync();

            var existentesSet = existentes
                .Select(o => (o.Sexo, o.EdadMeses, o.Tipo))
                .ToHashSet();

            bool Necesita(char sexo, int mes, TipoReferencia tipo) =>
                !existentesSet.Contains((sexo, mes, tipo));

            var nuevos = new List<OmsReferencia>();

            AgregarPesoM(nuevos, Necesita);
            AgregarPesoF(nuevos, Necesita);
            AgregarTallaM(nuevos, Necesita);
            AgregarTallaF(nuevos, Necesita);

            if (nuevos.Count == 0) return;

            await context.OmsReferencias.AddRangeAsync(nuevos);
            await context.SaveChangesAsync();
        }

        private static OmsReferencia R(char s, int e, TipoReferencia t,
            decimal p3, decimal p15, decimal p50, decimal p85, decimal p97) =>
            new() { Sexo = s, EdadMeses = e, Tipo = t,
                    Percentil3 = p3, Percentil15 = p15, Percentil50 = p50,
                    Percentil85 = p85, Percentil97 = p97 };

